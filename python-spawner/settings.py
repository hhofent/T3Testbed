def _map(value, fn):
    if isinstance(value,dict): return {k:_map(v,fn) for k,v in value.items()}
    if isinstance(value,(tuple,list)): return type(value)(_map(v,fn) for v in value)
    return fn(value)

def _limits(key,value,high):
    def leaf(v):
        if isinstance(v,bool): return high
        if isinstance(v,(int,float)):
            if key.endswith('invariants_numbers') or key in ('spawner.t','spawner.sf','spawner.grid','spawner.module') or abs(v)<=2: return v
            if 'pct' in key: return 100 if high else 0
            return max(v, v*2) if high else min(v,max(1,v/2))
        return v
    return _map(value,leaf)

